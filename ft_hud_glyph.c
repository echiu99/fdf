static void	ft_hud_dot(t_data *data, int x, int y)
{
	int	sx;
	int	sy;
	int	color;

	color = fdf_pack_rgb(0xFF, 0xFF, 0xFF);
	sy = 0;
	while (sy < FDF_GS)
	{
		sx = 0;
		while (sx < FDF_GS)
		{
			put_pixel_img(data, x + sx, y + sy, color);
			sx++;
		}
		sy++;
	}
}

void	ft_hud_putchar(t_data *data, int x, int y, char c)
{
	const unsigned char	*g;
	int					row;
	int					col;

	if (c < 32 || c > 126)
		c = '?';
	g = g_font[c - 32];
	row = 0;
	while (row < FDF_GH)
	{
		col = 0;
		while (col < FDF_GW)
		{
			if (g[row] & (0x10 >> col))
				ft_hud_dot(data, x + col * FDF_GS, y + row * FDF_GS);
			col++;
		}
		row++;
	}
}

void	ft_hud_putstr(t_data *data, int x, int y, char *s)
{
	int	i;

	i = 0;
	while (s[i])
	{
		ft_hud_putchar(data, x + i * ((FDF_GW + 1) * FDF_GS), y, s[i]);
		i++;
	}
}
