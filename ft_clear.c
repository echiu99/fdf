#include "fdf.h"

void	ft_clear_img(t_data *data)
{
	int	x;
	int	y;

	y = -1;
	while (y++ < data->h)
	{
		x = -1;
		while (x++ < data->w)
			put_pixel_img(data, x, y, FDF_COLOR_CLEAR);
	}
}
